#!/usr/bin/env python3
"""Writes FontDecompressorFixture.h: a three-group compressed 2-bit font and its glyphs.

    python3 test/font_decompressor/make_fixture.py > test/font_decompressor/FontDecompressorFixture.h

Each group holds its glyphs byte-aligned (each row padded to whole bytes) and is raw DEFLATE,
as lib/EpdFont/scripts/fontconvert.py writes them. The expected bitmaps are packed: rows run on
without padding, which is what FontDecompressor::getBitmap returns.
"""
import zlib

# (width, height) of each glyph; 6, 5 and 47 are not multiples of 4, so their rows are repacked.
SIZES = [(8, 3), (6, 4), (12, 2), (5, 5), (8, 8), (4, 1), (47, 40)]
GROUPS = [(0, 3), (3, 3), (6, 1)]  # (first glyph, glyph count); the last is big enough for back-references


def pixels(index, width, height):
    return [[((x * x + 3 * y * y) // 5 + index) % 4 for x in range(width)] for y in range(height)]


def aligned(px):
    out = bytearray()
    for row in px:
        padded = row + [0] * (-len(row) % 4)
        for i in range(0, len(padded), 4):
            out.append(padded[i] << 6 | padded[i + 1] << 4 | padded[i + 2] << 2 | padded[i + 3])
    return bytes(out)


def packed(px):
    bits = [v for row in px for v in row]
    bits += [0] * (-len(bits) % 4)
    return bytes(bits[i] << 6 | bits[i + 1] << 4 | bits[i + 2] << 2 | bits[i + 3] for i in range(0, len(bits), 4))


def array(name, data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i : i + 16]) for i in range(0, len(data), 16)]
    return f"inline constexpr uint8_t {name}[] = {{\n    " + ",\n    ".join(rows) + "};\n"


def main():
    glyphs = [pixels(i, w, h) for i, (w, h) in enumerate(SIZES)]
    compressed = bytearray()
    groups = []
    offsets = []
    for first, count in GROUPS:
        raw = bytearray()
        for i in range(first, first + count):
            offsets.append(len(raw))
            raw += aligned(glyphs[i])
        deflate = zlib.compressobj(9, zlib.DEFLATED, -15)
        body = deflate.compress(bytes(raw)) + deflate.flush()
        groups.append((len(compressed), len(body), len(raw), count, first))
        compressed += body

    print("// Generated by make_fixture.py; do not edit.")
    print("// clang-format off")
    print("#pragma once\n\n#include <cstdint>\n\n#include \"EpdFontData.h\"\n")
    print(array("kGroupData", compressed))
    print("inline constexpr EpdFontGroup kGroups[] = {")
    for g in groups:
        print(f"    {{{g[0]}, {g[1]}, {g[2]}, {g[3]}, {g[4]}}},")
    print("};\n")
    print("inline constexpr EpdGlyph kGlyphs[] = {")
    for i, (w, h) in enumerate(SIZES):
        print(f"    {{{w}, {h}, 0, 0, 0, {len(packed(glyphs[i]))}, {offsets[i]}}},")
    print("};\n")
    for i, px in enumerate(glyphs):
        print(array(f"kPacked{i}", packed(px)))
    print("inline constexpr const uint8_t* kPacked[] = {" + ", ".join(f"kPacked{i}" for i in range(len(SIZES))) + "};")
    print("// clang-format on")


if __name__ == "__main__":
    main()
