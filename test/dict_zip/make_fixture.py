#!/usr/bin/env python3
"""Writes DictZipFixture.h: a small dictzip file and the text it holds.

    python3 test/dict_zip/make_fixture.py > test/dict_zip/DictZipFixture.h

dictzip (https://linux.die.net/man/1/dictzip) is gzip whose FEXTRA "RA" field lists
the compressed length of each chunk. Every chunk but the last ends with a full flush, so
each can be inflated on its own as raw DEFLATE.
"""
import struct
import zlib

CHUNK_LENGTH = 3000


def text():
    words = ["kitap", "sözlük", "e-ink", "CrossPoint", "chunk", "inflate", "ağaç", "pencere"]
    lines = []
    for i in range(400):
        lines.append(f"{i:04d} {words[i % len(words)]} {words[(i * 7) % len(words)]} {i * i % 9973}\n")
    return "".join(lines).encode("utf-8")


def dictzip(data):
    deflate = zlib.compressobj(9, zlib.DEFLATED, -15)
    chunks = []
    for start in range(0, len(data), CHUNK_LENGTH):
        last = start + CHUNK_LENGTH >= len(data)
        body = deflate.compress(data[start : start + CHUNK_LENGTH])
        body += deflate.flush(zlib.Z_FINISH if last else zlib.Z_FULL_FLUSH)
        chunks.append(body)
    ra = struct.pack("<HHH", 1, CHUNK_LENGTH, len(chunks)) + b"".join(struct.pack("<H", len(c)) for c in chunks)
    extra = b"RA" + struct.pack("<H", len(ra)) + ra
    header = bytes([0x1F, 0x8B, 8, 0x04]) + bytes(4) + bytes([2, 3]) + struct.pack("<H", len(extra)) + extra
    trailer = struct.pack("<II", zlib.crc32(data), len(data))
    return header + b"".join(chunks) + trailer, header, chunks


def array(name, data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i : i + 16]) for i in range(0, len(data), 16)]
    return f"inline constexpr uint8_t {name}[] = {{\n    " + ",\n    ".join(rows) + "};\n"


def main():
    data = text()
    file, header, chunks = dictzip(data)
    offsets = [len(header)]
    for c in chunks:
        offsets.append(offsets[-1] + len(c))
    print("// Generated by make_fixture.py; do not edit.")
    print("// clang-format off")
    print("#pragma once\n\n#include <cstddef>\n#include <cstdint>\n")
    print(f"inline constexpr uint32_t kChunkLength = {CHUNK_LENGTH};")
    print(f"inline constexpr size_t kChunkCount = {len(chunks)};")
    print("// File offset of each chunk's compressed bytes, and of the trailer.")
    print(f"inline constexpr uint32_t kChunkFileOffsets[] = {{{', '.join(map(str, offsets))}}};")
    print(array("kDictZip", file))
    print(array("kDictText", data))
    print("// clang-format on")


if __name__ == "__main__":
    main()
