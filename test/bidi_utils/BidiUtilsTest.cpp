TEST(BidiVisual, PinnedCases) {
  for (const VisualCase& c : kVisualCases) {
    std::string out;
    const bool ok = BidiUtils::applyBidiVisual(encode(c.in).c_str(), out, c.level);
    EXPECT_EQ(ok, c.ok) << c.name;
    if (ok) {
      EXPECT_EQ(decode(out), c.out) << c.name;
    }
  }
}

TEST(BidiVisual, NullAndEmptyAreDeclined) {
  std::string out = "kept";
  EXPECT_FALSE(BidiUtils::applyBidiVisual(nullptr, out));
  EXPECT_FALSE(BidiUtils::applyBidiVisual("", out));
  EXPECT_EQ(out, "kept");
}

TEST(BidiVisual, InvalidUtf8EndsTheText) {
  std::string out;
  ASSERT_TRUE(BidiUtils::applyBidiVisual("\xD7\xA9\xD7\x9C\xFF\xD7\x95", out));
  EXPECT_EQ(decode(out), (CP{0x05DC, 0x05E9}));
}

TEST(BidiVisual, LongerThan128CharactersIsDeclined) {
  for (const uint32_t letter : {uint32_t{'a'}, uint32_t{0x05D0}}) {
    std::string out;
    EXPECT_TRUE(BidiUtils::applyBidiVisual(encode(CP(128, letter)).c_str(), out)) << letter;
    EXPECT_EQ(decode(out), CP(128, letter));
    EXPECT_FALSE(BidiUtils::applyBidiVisual(encode(CP(129, letter)).c_str(), out)) << letter;
  }
}

TEST(BidiWordOrder, PinnedCases) {
  for (const OrderCase& c : kOrderCases) {
    std::vector<uint16_t> order = {99};
    EXPECT_EQ(BidiUtils::computeVisualWordOrder(encodeWords(c.words), c.rtl, order), c.ok) << c.name;
    EXPECT_EQ(order, c.order) << c.name;
  }
}

TEST(BidiWordOrder, MoreThan128CharactersOrWordsIsDeclined) {
  std::vector<uint16_t> order;
  EXPECT_FALSE(BidiUtils::computeVisualWordOrder(encodeWords({CP(200, 'a'), {0x05D0}}), false, order));
  EXPECT_FALSE(BidiUtils::computeVisualWordOrder(std::vector<std::string>(129, "a"), true, order));
  EXPECT_TRUE(order.empty());
}

TEST(BidiProbe, PinnedCases) {
  for (const ProbeCase& c : kProbeCases) {
    EXPECT_EQ(BidiUtils::startsWithRtl(c.text), c.starts != 0) << c.text;
    EXPECT_EQ(BidiUtils::startsWithRtl(c.text, 2), c.startsWithin2 != 0) << c.text;
    EXPECT_EQ(BidiUtils::detectParagraphLevel(c.text), c.level) << c.text;
    EXPECT_EQ(BidiUtils::detectParagraphLevel(c.text, 1), c.levelOr1) << c.text;
    EXPECT_EQ(BidiUtils::detectParagraphLevel(c.text, 1, 2), c.levelOr1Within2) << c.text;
  }
  EXPECT_FALSE(BidiUtils::startsWithRtl(nullptr));
  EXPECT_EQ(BidiUtils::detectParagraphLevel(nullptr, 3), 1);
  EXPECT_EQ(BidiUtils::detectParagraphLevel("\xD7\xA9", 0, 0), 0) << "no probe depth";
}
