#!/usr/bin/env python3
"""Render src/images/logo.svg into the 1-bit boot and sleep logo.

Writes src/images/Logo120.png (upright, for the user guide) and
src/images/Logo120.h. GfxRenderer::drawImage does not rotate bits, so the
array holds the logo as the portrait screen shows it, turned 90 degrees
counter-clockwise into the panel's native orientation. A set bit is white.

Needs rsvg-convert (librsvg) and Pillow:
    python3 scripts/generate_logo.py
"""

import subprocess
import sys
import tempfile
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SVG = ROOT / "src/images/logo.svg"
PNG = ROOT / "src/images/Logo120.png"
HEADER = ROOT / "src/images/Logo120.h"
SIZE = 120
# Grey above this is white. Antialiased edges darker than it keep 2-pixel lines whole.
THRESHOLD = 160


def render() -> Image.Image:
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "logo.png"
        subprocess.run(
            ["rsvg-convert", "-b", "white", "-w", str(SIZE), "-h", str(SIZE), str(SVG), "-o", str(out)],
            check=True,
        )
        grey = Image.open(out).convert("L")
        return grey.point(lambda v: 255 if v > THRESHOLD else 0).convert("1")


def pack(image: Image.Image) -> bytes:
    width, height = image.size
    out = bytearray()
    for y in range(height):
        for x in range(0, width, 8):
            byte = 0
            for k in range(8):
                byte = (byte << 1) | (1 if x + k < width and image.getpixel((x + k, y)) else 0)
            out.append(byte)
    return bytes(out)


def main() -> int:
    logo = render()
    logo.save(PNG)
    data = pack(logo.transpose(Image.Transpose.ROTATE_90))
    rows = [", ".join(f"0x{b:02x}" for b in data[i : i + 19]) for i in range(0, len(data), 19)]
    HEADER.write_text(
        "#pragma once\n#include <cstdint>\n\n"
        "// Generated by scripts/generate_logo.py from logo.svg; do not edit.\n"
        f"// Image dimensions: {SIZE}x{SIZE}\n"
        "static const uint8_t Logo120[] = {\n" + "".join(f"    {row},\n" for row in rows) + "};\n"
    )
    print(f"wrote {PNG.relative_to(ROOT)} and {HEADER.relative_to(ROOT)} ({len(data)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
